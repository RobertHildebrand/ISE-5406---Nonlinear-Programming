function BoundChart({ rows, upperKey, lowerKey, upperLabel, lowerLabel, upperColor, lowerColor, invert }) {
  const W = 720, H = 220, padL = 60, padR = 16, padT = 14, padB = 30;
  const cw = W - padL - padR, ch = H - padT - padB;
  const N = rows.length;
  if (N === 0) return null;
  const upperVals = rows.map((r) => r[upperKey]);
  const lowerVals = rows.map((r) => r[lowerKey]);
  const all = [...upperVals, ...lowerVals];
  const yMin = Math.min(...all);
  const yMax = Math.max(...all);
  const xs = (i) => padL + (i / Math.max(1, N - 1)) * cw;
  const ys = (v) => padT + (1 - (v - yMin) / Math.max(1e-9, yMax - yMin)) * ch;

  return (
    <div style={panel}>
      <div style={{ fontFamily: "monospace", fontSize: 11, color: "#888", marginBottom: 4 }}>
        bound progression
      </div>
      <svg width={W} height={H}>
        <line x1={padL} y1={padT + ch} x2={padL + cw} y2={padT + ch} stroke="#bbb" />
        <line x1={padL} y1={padT} x2={padL} y2={padT + ch} stroke="#bbb" />
        {/* upper */}
        <polyline
          points={upperVals.map((v, i) => `${xs(i)},${ys(v)}`).join(" ")}
          fill="none"
          stroke={upperColor}
          strokeWidth={2}
        />
        {upperVals.map((v, i) => (
          <circle key={i} cx={xs(i)} cy={ys(v)} r={4} fill={upperColor} />
        ))}
        {/* lower */}
        <polyline
          points={lowerVals.map((v, i) => `${xs(i)},${ys(v)}`).join(" ")}
          fill="none"
          stroke={lowerColor}
          strokeWidth={2}
        />
        {lowerVals.map((v, i) => (
          <circle key={i} cx={xs(i)} cy={ys(v)} r={4} fill={lowerColor} />
        ))}
        {/* gap fill */}
        {upperVals.map((u, i) => {
          if (i === 0) return null;
          const u0 = upperVals[i - 1], u1 = u;
          const l0 = lowerVals[i - 1], l1 = lowerVals[i];
          const path = `M ${xs(i - 1)} ${ys(u0)} L ${xs(i)} ${ys(u1)} L ${xs(i)} ${ys(l1)} L ${xs(i - 1)} ${ys(l0)} Z`;
          return <path key={i} d={path} fill={upperColor + "11"} />;
        })}
        {/* y labels */}
        <text x={padL - 6} y={padT + 4} textAnchor="end" fontSize={10} fontFamily="monospace" fill="#666">
          {yMax.toFixed(2)}
        </text>
        <text x={padL - 6} y={padT + ch} textAnchor="end" fontSize={10} fontFamily="monospace" fill="#666">
          {yMin.toFixed(2)}
        </text>
        {/* legend */}
        <g transform={`translate(${padL + 12}, ${padT + 4})`}>
          <line x1={0} y1={6} x2={14} y2={6} stroke={upperColor} strokeWidth={2} />
          <text x={18} y={10} fontSize={10}>{upperLabel}</text>
          <line x1={130} y1={6} x2={144} y2={6} stroke={lowerColor} strokeWidth={2} />
          <text x={148} y={10} fontSize={10}>{lowerLabel}</text>
        </g>
      </svg>
    </div>
  );
}

function LagrangianChart({ history }) {
  const W = 720, H = 240, padL = 60, padR = 16, padT = 14, padB = 30;
  const cw = W - padL - padR, ch = H - padT - padB;
  if (history.length === 0) return null;

  // x-axis: lambda
  const lams = history.map((r) => r.lambda);
  const lows = history.map((r) => r.lower);
  const xMin = 0, xMax = Math.max(2, ...lams) * 1.1;
  const yMin = Math.min(...lows, 0);
  const yMax = Math.max(LAG_OPT * 1.05, ...lows);
  const xs = (v) => padL + ((v - xMin) / (xMax - xMin)) * cw;
  const ys = (v) => padT + (1 - (v - yMin) / Math.max(1e-9, yMax - yMin)) * ch;

  // Sample L(λ) curve — piecewise linear concave
  // Use the historical points + extend; pretend the dual is piecewise linear
  // through the visited points.
  const dualCurve = [...history].sort((a, b) => a.lambda - b.lambda);
  const dualPath = dualCurve.map((p) => `${xs(p.lambda)},${ys(p.lower)}`).join(" ");

  return (
    <div style={panel}>
      <div style={{ fontFamily: "monospace", fontSize: 11, color: "#888", marginBottom: 4 }}>
        Lagrangian dual function L(λ) — concave, piecewise linear
      </div>
      <svg width={W} height={H}>
        <line x1={padL} y1={padT + ch} x2={padL + cw} y2={padT + ch} stroke="#bbb" />
        <line x1={padL} y1={padT} x2={padL} y2={padT + ch} stroke="#bbb" />
        {/* IP optimum (target) */}
        <line x1={padL} y1={ys(LAG_OPT)} x2={padL + cw} y2={ys(LAG_OPT)} stroke="#c8311c" strokeWidth={2} strokeDasharray="6,4" />
        <text x={padL + cw - 6} y={ys(LAG_OPT) - 4} textAnchor="end" fontSize={10} fill="#c8311c">
          IP opt = {LAG_OPT}
        </text>
        {/* LP bound */}
        <line x1={padL} y1={ys(LAG_LP_BOUND)} x2={padL + cw} y2={ys(LAG_LP_BOUND)} stroke="#0b3da0" strokeWidth={1.5} strokeDasharray="3,3" />
        <text x={padL + cw - 6} y={ys(LAG_LP_BOUND) + 12} textAnchor="end" fontSize={10} fill="#0b3da0">
          LP bound = {LAG_LP_BOUND}
        </text>
        {/* dual curve */}
        <polyline points={dualPath} fill="none" stroke="#1f4e3d" strokeWidth={2.5} />
        {/* iterate path */}
        <polyline
          points={history.map((p) => `${xs(p.lambda)},${ys(p.lower)}`).join(" ")}
          fill="none"
          stroke="#7a3da0"
          strokeWidth={1.5}
          strokeDasharray="4,2"
        />
        {history.map((p, i) => (
          <g key={i}>
            <circle cx={xs(p.lambda)} cy={ys(p.lower)} r={i === history.length - 1 ? 6 : 4} fill={i === history.length - 1 ? "#c8311c" : "#1f4e3d"} stroke="#fff" strokeWidth={1.5} />
            <text x={xs(p.lambda) + 6} y={ys(p.lower) - 6} fontSize={9} fontFamily="monospace" fill="#444">
              k={p.it}
            </text>
          </g>
        ))}
        {/* axis labels */}
        <text x={padL + cw / 2} y={H - 6} textAnchor="middle" fontSize={11} fontFamily="monospace" fill="#444">
          λ
        </text>
        <text x={20} y={padT + ch / 2} textAnchor="middle" fontSize={11} fontFamily="monospace" fill="#444" transform={`rotate(-90, 20, ${padT + ch / 2})`}>
          L(λ)
        </text>
      </svg>
    </div>
  );
}

