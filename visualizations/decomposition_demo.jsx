/* ============================================================
   IP DECOMPOSITION ALGORITHMS
   ISE 5406

   Three classical decomposition methods, side-by-side:

     • BENDERS DECOMPOSITION
         max  c^T x + d^T y
         s.t. A x + B y <= b,  x ∈ X (integer),  y >= 0
       Project out y → master in x with optimality / feasibility cuts
       generated by solving the dual of the y-LP at each candidate x.

     • DANTZIG-WOLFE
         min  c^T x  s.t. A x = b,  D x <= e
       Block-diagonal D (subproblems) + linking A. Reformulate by
       expressing x as a convex combination of subproblem extreme
       points; master picks weights via column generation.

     • LAGRANGIAN RELAXATION
         min  c^T x  s.t. A x <= b,  x ∈ S (easy)
       Dualize Ax ≤ b: L(λ) = min_x c^T x + λ^T(Ax - b).
       Maximize L(λ) over λ ≥ 0 via subgradient ascent.
       Lower bound on the original min.

   Each tab shows: master/subproblem split, bound progression,
   per-iteration table.
   ============================================================ */

